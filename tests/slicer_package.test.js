// support-fins-slicer: the USB-stick file (web/slicer/package.js) and its MD5.
import { assert, assertEquals } from 'jsr:@std/assert';
import { md5Hex } from '../web/slicer/md5.js';
import { durationSeconds, gcodeStats, gcodeObjects, writeGcode3mf } from '../web/slicer/package.js';
import { unzip } from '../web/zip.js';

const enc = new TextEncoder();

Deno.test('md5Hex: RFC 1321 test vectors, uppercase as Bambu writes it', () => {
  assertEquals(md5Hex(enc.encode('')), 'D41D8CD98F00B204E9800998ECF8427E');
  assertEquals(md5Hex(enc.encode('abc')), '900150983CD24FB0D6963F7D28E17F72');
  assertEquals(md5Hex(enc.encode('message digest')), 'F96B697D7CB7938D525A2F31AAF161D0');
  assertEquals(md5Hex(enc.encode('12345678901234567890123456789012345678901234567890123456789012345678901234567890')),
    '57EDF4A22BE3C955AC49DA2E2107B67A');
});

Deno.test('durationSeconds reads the engine\'s time strings', () => {
  assertEquals(durationSeconds('1h 18m 41s'), 4721);
  assertEquals(durationSeconds('5m 8s'), 308);
  assertEquals(durationSeconds('2d 3h 4m 5s'), 2 * 86400 + 3 * 3600 + 245);
  assertEquals(durationSeconds(''), 0);
});

const GCODE = `; HEADER_BLOCK_START
; generated by OrcaSlicer 2.4.2
; model printing time: 1h 13m 32s; total estimated time: 1h 18m 41s
; estimated first layer printing time (normal mode) = 5m 8s
; total layer number: 395
; max_z_height: 79.20
; HEADER_BLOCK_END
; start printing object, unique label id: 22
G1 X1 Y1 E1
; stop printing object, unique label id: 22
; start printing object, unique label id: 21
; stop printing object, unique label id: 21
; start printing object, unique label id: 22
; filament used [mm] = 10759.44
; filament used [g] = 32.61
`;

Deno.test('gcodeStats and gcodeObjects read the comments the engine writes', () => {
  const s = gcodeStats(enc.encode(GCODE));
  assertEquals(s, { seconds: 4721, firstLayerSeconds: 308, layers: 395, maxZ: 79.2, filamentMm: 10759.44, filamentG: 32.61 });
  assertEquals(gcodeObjects(GCODE), ['22', '21']);
});

Deno.test('writeGcode3mf: Bambu sliced-3MF layout, MD5 of the G-code, X2D printer facts', async () => {
  const gcode = enc.encode(GCODE);
  const printer = { nozzle: 0.4, model_id: 'N6',
    physical: { extruder_type: ['Direct Drive', 'Bowden'], nozzle_diameter: ['0.4', '0.4'], extruder: 1 } };
  const filament = { tray_id: 'GFA00', config: { filament_type: ['PLA'] } };
  const blob = writeGcode3mf({ gcode, thumbnail: new Uint8Array([137, 80, 78, 71]),
    thumbnailSmall: new Uint8Array([137, 80, 78, 71, 1]), printer, filament,
    config: { layer_height: '0.2', nozzle_diameter: ['0.4'], curr_bed_type: 'Textured PEI Plate' }, stats: gcodeStats(gcode),
    objects: [{ id: '22', name: 'bowl' }, { id: '21', name: 'dome <1>' }],
    plate: { objects: [{ name: 'bowl', bbox: [100, 100, 120, 130] }, { name: 'dome <1>', bbox: [140, 90, 160, 110] }] },
    title: 'test' });
  const files = await unzip(new Uint8Array(await blob.arrayBuffer()));
  const get = (n) => (files.has(n) ? { data: files.get(n) } : null);   // unzip: Map name -> bytes
  for (const n of ['[Content_Types].xml', '_rels/.rels', '3D/3dmodel.model', 'Metadata/plate_1.gcode',
    'Metadata/plate_1.gcode.md5', 'Metadata/plate_1.png', 'Metadata/plate_1_small.png', 'Metadata/plate_1.json',
    'Metadata/model_settings.config', 'Metadata/_rels/model_settings.config.rels', 'Metadata/slice_info.config',
    'Metadata/project_settings.config']) {
    assert(get(n), `missing ${n}`);
  }
  const dec = new TextDecoder();
  assertEquals(dec.decode(get('Metadata/plate_1.gcode').data), GCODE);
  assertEquals(dec.decode(get('Metadata/plate_1.gcode.md5').data), md5Hex(gcode));
  const info = dec.decode(get('Metadata/slice_info.config').data);
  for (const s of ['key="printer_model_id" value="N6"', 'key="nozzle_diameters" value="0.4,0.4"',
    'key="extruder_type" value="0 1"', 'key="prediction" value="4721"', 'key="weight" value="32.61"',
    'key="filament_maps" value="1"', 'tray_info_idx="GFA00"', 'type="PLA"', 'identify_id="21" name="dome &lt;1&gt;"']) {
    assert(info.includes(s), `slice_info lacks ${s}`);
  }
  assert(info.includes('key="X-BBL-Client-Version" value="02.09.01.70"'));
  assert(info.includes('nozzle_diameter="0.40"'));
  assert(dec.decode(get('_rels/.rels').data).includes('/Metadata/plate_1_small.png'));
  assert(dec.decode(get('Metadata/model_settings.config').data).includes('key="gcode_file" value="Metadata/plate_1.gcode"'));
  const pj = JSON.parse(dec.decode(get('Metadata/plate_1.json').data));
  assertEquals(pj.bbox_all, [100, 90, 160, 130]);
  assertEquals(pj.bed_type, 'textured_plate');
  assertEquals(pj.first_extruder, 0);
  assertEquals(pj.bbox_objects.map((o) => o.area), [600, 400]);
  const settings = JSON.parse(dec.decode(get('Metadata/project_settings.config').data));
  assertEquals(settings.layer_height, '0.2');
  assertEquals(settings.nozzle_diameter, ['0.4']);
});
